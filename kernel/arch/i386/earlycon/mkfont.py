# characters unscii-16 has no glyph for, drawn here (public domain too)
DRAWN = {
    0x2302: [  # house
        "........", "........", "........", "........",
        "...##...", "..####..", ".##..##.", "##....##",
        "##....##", "##....##", "##....##", "########",
        "########", "........", "........", "........",
    ],
    0x2219: [  # bullet operator, between the middle dot and the bullet
        "........", "........", "........", "........",
        "........", "........", "...##...", "..####..",
        "..####..", "...##...", "........", "........",
        "........", "........", "........", "........",
    ],
}


def main():
    glyphs = {}
    for line in open(sys.argv[1]):
        code, bits = line.strip().split(":")
        if len(bits) == 32:
            glyphs[int(code, 16)] = bytes.fromhex(bits)

    for u, rows in DRAWN.items():
        glyphs[u] = bytes(int(r.replace(".", "0").replace("#", "1"), 2) for r in rows)

    # the sun with rays is the sun, the reversed not sign the mirrored one
    glyphs[0x263C] = glyphs[0x2609]
    glyphs[0x2310] = bytes(int(f"{b:08b}"[::-1], 2) for b in glyphs[0x00AC])

    print("/*")
    print(" * 8x16 font, the characters of code page 437 in order: generated by")
    print(" * mkfont.py from unscii-16 by Viznut (public domain,")
    print(" * https://viznut.fi/unscii/)")
    print(" */")
    print()
    print("const unsigned char font_8x16[256 * 16] = {")
    for i, u in enumerate(CP437):
        name = chr(u) if 0x20 < u < 0x7F and u != 0x5C else f"U+{u:04X}"
        print(f"    /* 0x{i:02X} {name} */")
        print("    " + ", ".join(f"0x{b:02X}" for b in glyphs[u]) + ",")
    print("};")


main()
