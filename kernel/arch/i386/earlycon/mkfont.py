#!/usr/bin/env python3
#
# Generates font.h, the 8x16 font of the early console and the virtual
# terminals, from unscii-16 (public domain, https://viznut.fi/unscii/):
# its glyphs for the 256 characters of code page 437, in that order.
#
# usage: mkfont.py unscii-16.hex > font.h
#
# unscii-16.hex is fontfiles/unscii-16.hex of https://github.com/viznut/unscii
# (not unscii-16-full, which has GPL glyphs from GNU Unifont).
#

